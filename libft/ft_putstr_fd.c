#include "libft.h"
#include <unistd.h>

// Step 1: guard against a NULL 's'.

// Step 2: write ft_strlen(s) bytes of 's' to 'fd' in one call.

void	ft_putstr_fd(char *s, int fd)
{
	size_t	len;

	if (!s)
		return ;
	len = ft_strlen(s);
	write(fd, s, len);
}
