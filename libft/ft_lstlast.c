#include "libft.h"

// Step 1: guard against an empty list (NULL 'lst') - there is no
//         last node to return.

// Step 2: walk forward via 'next' for as long as there is a next
//         node.

// Step 3: return the node whose 'next' is NULL - the last node.

t_list	*ft_lstlast(t_list *lst)
{
	if (!lst)
		return (NULL);
	while (lst->next)
		lst = lst->next;
	return (lst);
}
